#!/bin/sh
# Regenerate seedwords/seed-words.txt, the search-term list baked into the
# image (SEED_WORDS_FILE).
#
# Source: hermitdave/FrequencyWords, MIT licensed -- English word frequency
# counted from web text. The seeder turns these words into search queries, so
# a frequency list beats a dictionary list. The top of the list is function
# words ("the", "of"), which make useless queries, so ranks 501-30000 are kept.
#
# Why it is vendored: the dictionary URL the upstream script fetches
# (svnweb.freebsd.org .../share/dict/words) now answers a plain HTTP client
# with 404 and a browser-user-agent client with a bot-challenge page, and every
# line of whatever came back became a search term -- the seeder ended up
# querying minified JavaScript and burning minutes on bot-walled searches.
# See patches/0007-seed-word-list.patch.
#
# Usage:
#   tools/refresh_seedwords.sh
#
# Then commit the regenerated file. Check the diff: 15000 words, and they
# should read like things people actually search for.

set -eu

SOURCE_REPO="hermitdave/FrequencyWords"
SOURCE_FILE="content/2018/en/en_50k.txt"
LICENSE="MIT"
OUT="$(dirname "$0")/../seedwords/seed-words.txt"
URL="https://raw.githubusercontent.com/${SOURCE_REPO}/master/${SOURCE_FILE}"

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

echo "fetching $URL"
curl -fsSL "$URL" -o "$TMP"

{
    echo "# Vendored seed word list: random search terms for the link seeder."
    echo "# Source:   ${URL}"
    echo "# Ref:      master, 2018 English web-text frequency list (word + count)"
    echo "# License:  ${LICENSE} - https://github.com/${SOURCE_REPO}/blob/master/LICENSE"
    echo "# Fetched:  $(date -u '+%Y-%m-%d %H:%M UTC')"
    echo '# Filter:   frequency rank 501-30000 (the top of the list is function words:'
    echo '#           "the", "of"), 3-14 letters, lowercase, source order, 15000 kept'
    echo "# Generated by: tools/refresh_seedwords.sh"

    # "$1" is the word; the count column is dropped. CRLF from the CDN is removed
    # before the word-shaped filter, which would otherwise reject every line.
    awk 'NR >= 501 && NR <= 30000 { print $1 }' "$TMP" | tr -d '\r' \
        | awk '$0 ~ /^[a-z]+$/ && length($0) >= 3 && length($0) <= 14' \
        | head -15000
} > "$OUT.tmp"

mv "$OUT.tmp" "$OUT"
echo "wrote $OUT: $(grep -cv '^#' "$OUT" | tr -d ' ') words"
