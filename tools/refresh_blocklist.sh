#!/bin/sh
# Regenerate blocklist/blocklist-domains.txt, the domain filter baked into the
# image (BLACKLIST=local).
#
# Source: the unified StevenBlack/hosts file, MIT licensed and safe to
# redistribute with attribution. It carries ad, tracker and malware domains --
# exactly the categories this container needs to keep out of its fake traffic.
#
# It replaces the old Shalla lists, which are (a) gone, (b) 93% content
# categories this script does not care about, and (c) explicitly not
# redistributable ("The lists must not be given to any third party").
#
# Usage:
#   tools/refresh_blocklist.sh              # refresh from the current upstream
#   SOURCE_COMMIT=<sha> tools/refresh_blocklist.sh
#
# Then commit the regenerated file. Check the diff before pushing: the domain
# count should move by a few thousand, not by half.

set -eu

SOURCE_REPO="StevenBlack/hosts"
SOURCE_FILE="hosts"
LICENSE="MIT"
OUT="$(dirname "$0")/../blocklist/blocklist-domains.txt"

if [ -n "${SOURCE_COMMIT:-}" ]; then
    REF="$SOURCE_COMMIT"
else
    REF="master"
fi
URL="https://raw.githubusercontent.com/${SOURCE_REPO}/${REF}/${SOURCE_FILE}"

TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

echo "fetching $URL"
curl -fsSL "$URL" -o "$TMP"

# Keep the domain from "0.0.0.0 example.com" / "::1 example.com" lines, drop
# loopback and broadcast entries, keep the upstream provenance header comment.
{
    echo "# Vendored domain blocklist used when BLACKLIST=local."
    echo "# Source:   https://github.com/${SOURCE_REPO} (${SOURCE_FILE})"
    echo "# Ref:      ${REF}"
    echo "# License:  ${LICENSE} - https://github.com/${SOURCE_REPO}/blob/master/license.txt"
    echo "# Fetched:  $(date -u '+%Y-%m-%d %H:%M UTC')"
    echo "# Generated by: tools/refresh_blocklist.sh"
    echo "# Format:   one domain per line; # starts a comment."
    grep -E '^# ' "$TMP" | head -20
    echo ""
    awk '
        /^0\.0\.0\.0[ \t]/ || /^::1[ \t]/ {
            domain = $NF
            if (domain !~ /\// && domain != "localhost" && domain != "localhost.localdomain" \
                && domain != "broadcasthost" && domain != "local") {
                print domain
            }
        }
    ' "$TMP" | sort -u
} > "$OUT.tmp"

mv "$OUT.tmp" "$OUT"
echo "wrote $OUT: $(grep -cv '^#' "$OUT" | tr -d ' ') non-comment lines"
